import json
import sys
from pathlib import Path

import joblib
import pandas as pd


# ---------------------------------------------------------
# 1. Define file locations and model features
# ---------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent

CSV_FILE = BASE_DIR / "processed" / "intersection_sites.csv"
RECORD_FILE = BASE_DIR / "output" / "site_record.json"

MODEL_FILE = BASE_DIR / "models" / "best_model.joblib"

OUTPUT_DIR = BASE_DIR / "output"
PREDICTION_FILE = OUTPUT_DIR / "ml_prediction.json"
FACTS_FILE = OUTPUT_DIR / "ml_prediction_facts.pl"

NUMERIC_FEATURES = [
    "n_points",
    "point_spread_m",
    "spread_flag",
    "entering_aadt",
    "major_road_aadt",
    "n_state_roads",
    "cv_percent",
    "volume_stale",
    "has_volume",
    "ped_crossings_200m",
    "school_crossings_300m",
    "dist_school_crossing_m",
    "dist_cbd_km",
    "lon",
    "lat",
]

CATEGORICAL_FEATURES = [
    "site_type",
    "road_no",
]

FEATURES = NUMERIC_FEATURES + CATEGORICAL_FEATURES


# ---------------------------------------------------------
# 2. Load the selected site
# ---------------------------------------------------------

def load_selected_site():
    """Read the site key generated by prepare_site.py."""

    if not RECORD_FILE.is_file():
        raise FileNotFoundError(
            f"Site record not found: {RECORD_FILE}\n"
            "Run prepare_site.py before running this file."
        )

    with RECORD_FILE.open("r", encoding="utf-8") as handle:
        record = json.load(handle)

    site_key = record.get("site_key")

    if not site_key:
        raise ValueError(
            "site_record.json does not contain a site_key."
        )

    return record


# ---------------------------------------------------------
# 3. Load the matching CSV row and prepare model features
# ---------------------------------------------------------

def load_features(site_key, features):
    """Find the selected site and prepare the model's input columns."""

    if not CSV_FILE.is_file():
        raise FileNotFoundError(
            f"Intersection dataset not found: {CSV_FILE}"
        )

    data = pd.read_csv(CSV_FILE, encoding="utf-8-sig")

    required_columns = ["site_key"] + features
    missing_columns = [
        column for column in required_columns
        if column not in data.columns
    ]

    if missing_columns:
        raise ValueError(
            "The dataset is missing required columns: "
            + ", ".join(missing_columns)
        )

    matching_rows = data[
        data["site_key"].astype(str).str.strip() == site_key
    ]

    if matching_rows.empty:
        raise ValueError(
            f"Site key {site_key!r} was not found in the dataset."
        )

    # Use the first matching record, as in the preparation pipeline.
    row = matching_rows.iloc[[0]].copy()

    # Convert numeric inputs to numbers.
    # Invalid or blank values become NaN and are handled by the
    # imputation steps in the saved model pipeline.
    for column in features:
        if column not in NUMERIC_FEATURES:
            continue
        row[column] = pd.to_numeric(
            row[column],
            errors="coerce"
        )

    # Keep categorical fields as strings while preserving missing values.
    for column in features:
        if column in NUMERIC_FEATURES:
            continue
        row[column] = row[column].where(
            row[column].notna(),
            None
        )

    return row[features]


# ---------------------------------------------------------
# 4. Generate the machine-learning prediction
# ---------------------------------------------------------

def load_model():
    """Load the saved pipeline trained by train_models.py."""

    if not MODEL_FILE.is_file():
        raise FileNotFoundError(
            f"Trained model not found: {MODEL_FILE}\n"
            "Run train_models.py successfully first."
        )

    return joblib.load(MODEL_FILE)


def predict_site(model, features):
    """Return the model's class and positive-class probability."""

    predicted_class = int(model.predict(features)[0])

    # Find the probability corresponding specifically to class 1.
    probabilities = model.predict_proba(features)[0]
    model_classes = list(model.classes_)

    positive_index = model_classes.index(1)
    positive_probability = float(probabilities[positive_index])

    return predicted_class, positive_probability


# ---------------------------------------------------------
# 5. Save the prediction for Python and Prolog
# ---------------------------------------------------------

def save_prediction(record, predicted_class, probability):
    """Write a JSON result and corresponding Prolog facts."""

    site_id = record["prolog_site_id"]

    # Validate the generated identifier before using it in Prolog.
    allowed_characters = set(
        "abcdefghijklmnopqrstuvwxyz"
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        "0123456789_"
    )

    if (
        not site_id
        or site_id[0].isdigit()
        or not all(char in allowed_characters for char in site_id)
    ):
        raise ValueError(
            "The selected site's Prolog identifier is invalid."
        )

    classification = (
        "historical_fsi_present"
        if predicted_class == 1
        else "historical_fsi_absent"
    )

    result = {
        "site_key": record["site_key"],
        "prolog_site_id": site_id,
        "description": record.get("description", ""),
        "model": "Logistic Regression",
        "target": "any_fsi",
        "predicted_class": predicted_class,
        "classification": classification,
        "estimated_probability_any_fsi": round(probability, 6),
        "interpretation": (
            "Estimated probability of the positive historical "
            "any_fsi class in the dataset."
        ),
        "limitation": (
            "This model classifies historical crash labels. "
            "It is not a validated prediction of future crashes "
            "or an independent road-safety assessment."
        ),
    }

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    with PREDICTION_FILE.open("w", encoding="utf-8") as handle:
        json.dump(result, handle, indent=2)
        handle.write("\n")

    # These facts are designed to be consulted by the Prolog rules
    # in the next integration step.
    facts = [
        "% Generated by predict_site.py. Do not edit manually.",
        f"ml_classification({site_id}, {classification}).",
        (
            f"ml_positive_probability({site_id}, "
            f"{probability:.6f})."
        ),
    ]

    FACTS_FILE.write_text(
        "\n".join(facts) + "\n",
        encoding="utf-8"
    )

    return result


# ---------------------------------------------------------
# 6. Run the prediction
# ---------------------------------------------------------

def main():
    """Run the complete prediction process."""

    try:
        record = load_selected_site()
        model = load_model()
        # Use the exact columns the pipeline was trained on.
        features = load_features(
            record["site_key"],
            list(model.feature_names_in_)
        )

        predicted_class, probability = predict_site(model, features)

        result = save_prediction(
            record,
            predicted_class,
            probability
        )

    except (
        FileNotFoundError,
        ValueError,
        KeyError,
        OSError,
    ) as error:
        print("Prediction failed:")
        print(error)
        raise SystemExit(1)

    except Exception as error:
        print("Prediction failed because of an unexpected error:")
        print(error)
        raise SystemExit(1)

    print("Machine-learning prediction")
    print("----------------------------")
    print("Site:", result["site_key"])
    print("Description:", result["description"])
    print("Model:", result["model"])
    print("Predicted class:", result["classification"])
    print(
        "Estimated probability of positive class:",
        f"{result['estimated_probability_any_fsi']:.2%}"
    )
    print()
    print("JSON saved to:", PREDICTION_FILE)
    print("Prolog facts saved to:", FACTS_FILE)
    print()
    print("Note:", result["limitation"])


if __name__ == "__main__":
    main()
